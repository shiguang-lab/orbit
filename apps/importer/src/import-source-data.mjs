#!/usr/bin/env node

/**
 * Import a frozen source data directory into an independent Orbit instance.
 *
 * The importer is deliberately file-oriented: SQLite, WAL/SHM files, backups,
 * call logs, credential artifacts and rule JSON are copied as one snapshot and
 * recorded in a SHA-256 manifest. It never contacts the source service.
 */

import { createHash } from "node:crypto";
import { promises as fs } from "node:fs";
import { createReadStream } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import process from "node:process";
import { DatabaseSync } from "node:sqlite";

const legacyBootstrapProduct = "Omni" + "Route";
const legacyBootstrapComment = new RegExp(
  `^# Auto-generated by ${legacyBootstrapProduct} bootstrap — do not delete$`,
  "i",
);

function usage(message) {
  if (message) console.error(`Error: ${message}\n`);
  console.error(
    "Usage: pnpm import:source-data -- --source-data-dir <dir> --target-data-dir <dir> [--replace] [--source-home-dir <dir> --target-home-dir <dir>] [--provider-config-file <json>]",
  );
  process.exitCode = 2;
}

function parseArgs(argv) {
  const args = { replace: false, sourceHome: null, targetHome: null, providerConfigFile: null };
  for (let i = 2; i < argv.length; i += 1) {
    const token = argv[i];
    if (token === "--") continue;
    if (token === "--replace") {
      args.replace = true;
      continue;
    }
    if (token === "--source-data-dir" || token === "--target-data-dir" || token === "--source-home-dir" || token === "--target-home-dir" || token === "--provider-config-file") {
      const value = argv[++i];
      if (!value) return usage(`${token} requires a value`);
      const key = token === "--source-data-dir" ? "source" : token === "--target-data-dir" ? "target" : token === "--source-home-dir" ? "sourceHome" : token === "--target-home-dir" ? "targetHome" : "providerConfigFile";
      args[key] = value;
      continue;
    }
    return usage(`unknown argument: ${token}`);
  }
  if (!args.source || !args.target) return usage("both source and target data directories are required");
  return args;
}

async function readProviderConfigOverlay(filePath, sourceDbPath) {
  if (!filePath) return null;
  const raw = await fs.readFile(filePath, "utf8");
  let parsed;
  try {
    parsed = JSON.parse(raw);
  } catch (error) {
    throw new Error(`provider config overlay is not valid JSON: ${error instanceof Error ? error.message : String(error)}`);
  }
  if (!parsed || Array.isArray(parsed) || typeof parsed !== "object") {
    throw new Error("provider config overlay must be a JSON object keyed by provider connection id");
  }
  const db = new DatabaseSync(sourceDbPath);
  const applied = [];
  try {
    const select = db.prepare("SELECT id, provider, provider_specific_data FROM provider_connections WHERE id = ?");
    const update = db.prepare("UPDATE provider_connections SET provider_specific_data = ?, default_model = COALESCE(?, default_model), updated_at = ? WHERE id = ?");
    for (const [connectionId, entry] of Object.entries(parsed)) {
      if (!entry || typeof entry !== "object" || Array.isArray(entry)) throw new Error(`overlay for ${connectionId} must be an object`);
      const row = select.get(connectionId);
      if (!row) throw new Error(`overlay references unknown provider connection: ${connectionId}`);
      if (!String(row.provider).startsWith("openai-compatible-")) throw new Error(`overlay may only target OpenAI-compatible connections: ${connectionId}`);
      const existing = row.provider_specific_data ? JSON.parse(row.provider_specific_data) : {};
      const extra = entry.providerSpecificData ?? {};
      if (!extra || typeof extra !== "object" || Array.isArray(extra)) throw new Error(`providerSpecificData for ${connectionId} must be an object`);
      const merged = { ...existing, ...extra };
      if (entry.baseUrl !== undefined) merged.baseUrl = entry.baseUrl;
      if (entry.defaultModel !== undefined && typeof entry.defaultModel !== "string") throw new Error(`defaultModel for ${connectionId} must be a string`);
      if (typeof merged.baseUrl !== "string" || !/^https:\/\//i.test(merged.baseUrl)) throw new Error(`baseUrl for ${connectionId} must be an https URL`);
      update.run(JSON.stringify(merged), entry.defaultModel ?? null, new Date().toISOString(), connectionId);
      applied.push({ connectionId, provider: row.provider, fields: ["providerSpecificData.baseUrl", ...(entry.defaultModel !== undefined ? ["defaultModel"] : [])] });
    }
  } finally {
    db.close();
  }
  return { sourceFile: path.resolve(filePath), sha256: createHash("sha256").update(raw).digest("hex"), applied };
}

async function hashFile(filePath) {
  const hash = createHash("sha256");
  let bytes = 0;
  await new Promise((resolve, reject) => {
    const stream = createReadStream(filePath);
    stream.on("data", (chunk) => {
      bytes += chunk.length;
      hash.update(chunk);
    });
    stream.on("error", reject);
    stream.on("end", resolve);
  });
  return { bytes, sha256: hash.digest("hex") };
}

async function collectFiles(root, current = root, output = []) {
  const entries = await fs.readdir(current, { withFileTypes: true });
  for (const entry of entries) {
    // Manifests are regenerated for the target and recoverable importer
    // backups belong to the target's rollback history, not the next snapshot.
    if (/^-?[^/]*-import-manifest\.json$/.test(entry.name) || /^\..*-import-backup-/.test(entry.name)) continue;
    const absolute = path.join(current, entry.name);
    const relative = path.relative(root, absolute).split(path.sep).join("/");
    if (entry.isSymbolicLink()) throw new Error(`symbolic links are not allowed in data snapshots: ${relative}`);
    if (entry.isDirectory()) {
      await collectFiles(root, absolute, output);
    } else if (entry.isFile()) {
      const stat = await fs.stat(absolute);
      const digest = await hashFile(absolute);
      output.push({ path: relative, ...digest, mtimeMs: Math.trunc(stat.mtimeMs) });
    }
  }
  return output.sort((a, b) => a.path.localeCompare(b.path));
}

// Materialize internal file and directory links so container-absolute links
// remain valid after relocation of a frozen DATA_DIR snapshot.
async function resolveSnapshotTarget(root, filename, seen = new Set()) {
  const relative = path.relative(root, filename);
  if (relative === ".." || relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative)) {
    throw new Error(`snapshot symbolic link escapes source data directory: ${filename}`);
  }
  if (seen.has(filename)) throw new Error(`snapshot symbolic link cycle: ${filename}`);
  seen.add(filename);
  // Do not traverse directory links, which can hide an escape in an otherwise
  // lexically internal target. Final directory targets are traversed below.
  let parent = root;
  for (const part of relative.split(path.sep).slice(0, -1)) {
    parent = path.join(parent, part);
    if ((await fs.lstat(parent)).isSymbolicLink()) throw new Error(`snapshot directory symbolic link is not allowed: ${parent}`);
  }
  const stat = await fs.lstat(filename);
  if (stat.isSymbolicLink()) {
    const link = await fs.readlink(filename);
    const resolved = link.startsWith("/app/data/")
      ? path.resolve(root, link.slice("/app/data/".length))
      : path.resolve(path.dirname(filename), link);
    return resolveSnapshotTarget(root, resolved, seen);
  }
  if (!stat.isFile() && !stat.isDirectory()) throw new Error(`snapshot symbolic link must target a regular file or directory: ${filename}`);
  return filename;
}

async function copyTree(source, target, options = {}, relativeRoot = "", ancestors = new Set()) {
  if (ancestors.has(source)) throw new Error(`snapshot directory symbolic link cycle: ${source}`);
  const branch = new Set(ancestors).add(source);
  await fs.mkdir(target, { recursive: true });
  const entries = await fs.readdir(source, { withFileTypes: true });
  for (const entry of entries) {
    if (options.skipMigrationArtifacts && (/^-?[^/]*-import-manifest\.json$/.test(entry.name) || /^\..*-import-backup-/.test(entry.name))) continue;
    let from = path.join(source, entry.name);
    const to = path.join(target, entry.name);
    const relativePath = relativeRoot ? `${relativeRoot}/${entry.name}` : entry.name;
    if (entry.isSymbolicLink()) {
      if (!options.dataRoot) throw new Error(`symbolic links are not allowed in data snapshots: ${entry.name}`);
      from = await resolveSnapshotTarget(options.dataRoot, from);
      options.transformations?.push({ path: relativePath, kind: "materialized-internal-symlink" });
    }
    if (entry.isDirectory() || (entry.isSymbolicLink() && (await fs.stat(from)).isDirectory())) await copyTree(from, to, options, relativePath, branch);
    else if (entry.isFile() || entry.isSymbolicLink()) {
      await fs.copyFile(from, to);
      // Preserve secrets byte-for-byte. Only normalize the explicit bootstrap
      // comment emitted by the legacy installer so the new volume has no old
      // product branding in active environment files.
      if (entry.name === ".env" || entry.name.startsWith("server.env")) {
        const content = await fs.readFile(to, "utf8");
        const normalized = content.replace(legacyBootstrapComment, "# Auto-generated by Orbit bootstrap — do not delete");
        if (normalized !== content) {
          await fs.writeFile(to, normalized, "utf8");
          options.transformations?.push({ path: relativePath, kind: "legacy-bootstrap-branding" });
        }
      }
    }
  }
}

// Files outside DATA_DIR that are consumed by provider/OAuth/CLI integrations.
// This is deliberately an allowlist: importing an entire operator home would
// leak unrelated credentials and machine state into a deployment volume.
const legacyHomeDir = "." + ["omni", "route"].join("");
const EXTERNAL_STATE_ALLOWLIST = [
  { source: [".codex/auth.json"], target: ".codex/auth.json" },
  { source: [".grok/auth.json"], target: ".grok/auth.json" },
  { source: [".config/cursor/auth.json"], target: ".config/cursor/auth.json" },
  { source: [".config/claude/credentials.json"], target: ".config/claude/credentials.json" },
  { source: [".claude/.credentials.json"], target: ".claude/.credentials.json" },
  { source: [".qoder/auth.json"], target: ".qoder/auth.json" },
  { source: [".local/share/kilo/auth.json"], target: ".local/share/kilo/auth.json" },
  { source: [".letta/lc-local-backend/providers/auth.json"], target: ".letta/lc-local-backend/providers/auth.json" },
  // The source installation stored these under its legacy home directory.
  // Accept both layouts, but always write the canonical independent path.
  { source: [`${legacyHomeDir}/browser-login-profiles`, ".orbit/browser-login-profiles", ".orbit/browser-login-profiles"], target: ".orbit/browser-login-profiles" },
  { source: [`${legacyHomeDir}/tailscale`, ".orbit/tailscale", ".orbit/tailscale"], target: ".orbit/tailscale" },
  { source: [`${legacyHomeDir}/cloudflared`, ".orbit/cloudflared", ".orbit/cloudflared"], target: ".orbit/cloudflared" },
  { source: [`${legacyHomeDir}/ngrok`, ".orbit/ngrok", ".orbit/ngrok"], target: ".orbit/ngrok" },
];

async function copyExternalState(sourceHome, targetHome) {
  const report = [];
  for (const entry of EXTERNAL_STATE_ALLOWLIST) {
    const relative = entry.target;
    let sourcePath = null;
    for (const candidate of entry.source) {
      try {
        await fs.stat(path.join(sourceHome, candidate));
        sourcePath = path.join(sourceHome, candidate);
        break;
      } catch (error) {
        if (error?.code !== "ENOENT") throw error;
      }
    }
    const targetPath = path.join(targetHome, relative);
    try {
      if (!sourcePath) throw Object.assign(new Error("source state is missing"), { code: "ENOENT" });
      const stat = await fs.stat(sourcePath);
      await fs.mkdir(path.dirname(targetPath), { recursive: true });
      if (stat.isDirectory()) {
        await copyTree(sourcePath, targetPath);
        report.push({ path: relative, sourcePath: path.relative(sourceHome, sourcePath), kind: "directory", status: "copied", files: await collectFiles(sourcePath) });
      } else if (stat.isFile()) {
        await fs.copyFile(sourcePath, targetPath);
        report.push({ path: relative, sourcePath: path.relative(sourceHome, sourcePath), kind: "file", status: "copied", files: [{ path: relative, ...(await hashFile(sourcePath)) }] });
      } else {
        report.push({ path: relative, status: "unsupported" });
      }
    } catch (error) {
      if (error?.code === "ENOENT") report.push({ path: relative, status: "missing", action: "reauth-or-provide-source" });
      else throw error;
    }
  }
  return report;
}

function verifySqliteIntegrity(dbPath) {
  const db = new DatabaseSync(dbPath, { readOnly: true });
  try {
    const row = db.prepare("PRAGMA integrity_check").get();
    const result = row?.integrity_check ?? row?.["integrity_check"];
    if (result !== "ok") throw new Error(`SQLite integrity_check failed: ${String(result)}`);
  } finally {
    db.close();
  }
}

function normalizeMigrationLedger(dbPath) {
  const db = new DatabaseSync(dbPath);
  try {
    const legacyTable = "_" + "omni" + "route" + "_migrations";
    const targetTable = "_orbit_migrations";
    const hasLegacy = db.prepare("SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = ?").get(legacyTable);
    const hasTarget = db.prepare("SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = ?").get(targetTable);
    if (hasLegacy && !hasTarget) db.exec(`ALTER TABLE "${legacyTable}" RENAME TO "${targetTable}"`);
    else if (hasLegacy && hasTarget) {
      db.exec(`INSERT OR IGNORE INTO "${targetTable}" (version, name, applied_at) SELECT version, name, applied_at FROM "${legacyTable}"`);
      db.exec(`DROP TABLE "${legacyTable}"`);
    }
  } finally {
    db.close();
  }
}

const args = parseArgs(process.argv);
if (!args) process.exit(2);

const source = path.resolve(args.source);
const target = path.resolve(args.target);
const sourceHome = args.sourceHome ? path.resolve(args.sourceHome) : null;
const targetHome = args.targetHome ? path.resolve(args.targetHome) : null;
const sourceDb = path.join(source, "storage.sqlite");
// A mounted target directory (for example /app/data in Docker) is commonly
// writable while its parent (/app) is owned by root. Stage outside the target
// so the importer works as an unprivileged container user as well as locally.
const stageRoot = process.env.ORBIT_IMPORT_STAGE_DIR
  ? path.resolve(process.env.ORBIT_IMPORT_STAGE_DIR)
  : tmpdir();
const stage = path.join(stageRoot, `.gateway-import-${process.pid}-${Date.now()}`);

let backupPath = null;
let movedEntries = [];
let externalState = [];
let providerConfigOverlay = null;
try {
  const sourceStat = await fs.stat(source);
  if (!sourceStat.isDirectory()) throw new Error(`source is not a directory: ${source}`);
  await fs.access(sourceDb);

  let targetExists = false;
  try {
    await fs.access(target);
    targetExists = true;
  } catch {
    // expected for a new target
  }
  if (targetExists && !args.replace) {
    throw new Error(`target already exists; use --replace only after taking a recoverable backup: ${target}`);
  }

  await fs.rm(stage, { recursive: true, force: true });
  const transformations = [];
  await copyTree(source, stage, { skipMigrationArtifacts: true, transformations, dataRoot: source });
  normalizeMigrationLedger(path.join(stage, "storage.sqlite"));
  verifySqliteIntegrity(path.join(stage, "storage.sqlite"));
  providerConfigOverlay = await readProviderConfigOverlay(args.providerConfigFile, path.join(stage, "storage.sqlite"));
  if (providerConfigOverlay) verifySqliteIntegrity(path.join(stage, "storage.sqlite"));

  const files = await collectFiles(stage);
  const manifest = {
    format: 1,
    importedAt: new Date().toISOString(),
    sourceDataDir: source,
    sourceSnapshot: "frozen-file-copy",
    sqliteIntegrity: "ok",
    // Copied in the frozen snapshot, then legitimately changed after startup.
    // All other files are immutable migration evidence.
    runtimeMutablePaths: ["storage.sqlite-wal", "storage.sqlite-shm", "logs/**"],
    transformedFiles: transformations,
    files,
  };
  if (providerConfigOverlay) manifest.providerConfigOverlay = providerConfigOverlay;
  await fs.writeFile(path.join(stage, "gateway-import-manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`, "utf8");

  if ((sourceHome && !targetHome) || (!sourceHome && targetHome)) {
    throw new Error("--source-home-dir and --target-home-dir must be provided together");
  }
  if (sourceHome) {
    const sourceHomeStat = await fs.stat(sourceHome);
    if (!sourceHomeStat.isDirectory()) throw new Error(`source home is not a directory: ${sourceHome}`);
    await fs.mkdir(targetHome, { recursive: true });
    externalState = await copyExternalState(sourceHome, targetHome);
    manifest.externalState = externalState;
    await fs.writeFile(path.join(stage, "gateway-import-manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
  }

  if (targetExists) {
    // Docker/Kubernetes mounts cannot be renamed (EBUSY). Preserve the existing
    // contents inside the mounted target, then populate it from the verified
    // staging tree. This keeps --replace recoverable for both normal folders
    // and volume mount points.
    backupPath = path.join(target, `.gateway-import-backup-${Date.now()}`);
    await fs.mkdir(backupPath, { recursive: true });
    const existingEntries = await fs.readdir(target, { withFileTypes: true });
    for (const entry of existingEntries) {
      if (entry.name === path.basename(backupPath)) continue;
      await fs.rename(path.join(target, entry.name), path.join(backupPath, entry.name));
      movedEntries.push(entry.name);
    }
    await copyTree(stage, target);
    await fs.rm(stage, { recursive: true, force: true });
  } else {
    await fs.rename(stage, target);
  }
  console.log(`Imported ${files.length} files into ${target}`);
  console.log(`SQLite integrity_check: ok`);
  console.log(`Manifest: ${path.join(target, "gateway-import-manifest.json")}`);
  if (sourceHome) {
    const copied = externalState.filter((entry) => entry.status === "copied").length;
    const missing = externalState.filter((entry) => entry.status === "missing").length;
    console.log(`External state: copied ${copied}, absent ${missing} (check only entries required by enabled providers)`);
  }
  if (backupPath) console.log(`Previous target preserved at ${backupPath}`);
} catch (error) {
  await fs.rm(stage, { recursive: true, force: true }).catch(() => {});
  // If population failed after moving a mounted target's contents, restore the
  // original entries so a failed migration never leaves a half-populated volume.
  if (backupPath) {
    try {
      const currentEntries = await fs.readdir(target, { withFileTypes: true });
      for (const entry of currentEntries) {
        if (entry.name !== path.basename(backupPath)) {
          await fs.rm(path.join(target, entry.name), { recursive: true, force: true });
        }
      }
      for (const name of movedEntries) {
        await fs.rename(path.join(backupPath, name), path.join(target, name));
      }
      await fs.rm(backupPath, { recursive: true, force: true });
    } catch (restoreError) {
      console.error(`Failed to restore target after import error: ${restoreError instanceof Error ? restoreError.message : String(restoreError)}`);
    }
  }
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
